// Edições integrais em português. O ano se refere à obra, não à digitalização.
function livro(id, gutenbergId, title, year, author, description, tags) {
  const edition = `https://www.gutenberg.org/ebooks/${gutenbergId}`
  return {
    id, title, year, author, description, tags,
    type: 'livro',
    code: `BOOK_${year}_${id}`,
    availability: 'available',
    language: 'Português',
    rightsNote: 'Edição digital disponibilizada pelo Project Gutenberg. Os créditos da transcrição e as condições de uso acompanham o texto.',
    sources: [{ title: 'Project Gutenberg — edição e formatos de leitura', url: edition }],
    media: [{
      kind: 'text',
      title: 'Ler em português',
      path: `media/book-${gutenbergId}.txt`,
      remoteUrl: `https://www.gutenberg.org/cache/epub/${gutenbergId}/pg${gutenbergId}.txt`,
      sourceUrl: edition,
      license: 'Project Gutenberg — créditos e condições na edição de origem.',
      language: 'Português',
    }],
  }
}

function dossie(id, title, year, slug, archive, genre, description, note, recoveryStatus) {
  return {
    id, title, year, description, recoveryStatus,
    type: 'lost-media',
    code: `DOSSIER_${year}_${id}`,
    availability: 'available',
    language: 'Português',
    tags: ['preservação', 'cinema mudo', 'Nova Zelândia', genre],
    rightsNote: 'Dossiê editorial do SYSTEM 84. A cópia e as notas técnicas podem ser consultadas na instituição indicada.',
    sources: [{
      title: 'National Film Preservation Foundation — cópia e documentação',
      url: `https://www.filmpreservation.org/preserved-films/screening-room/${slug}`,
    }],
    media: [copiaPreservada(id, title)],
    article: [description, note, `Instituição responsável pela preservação desta cópia: ${archive}.`],
  }
}

